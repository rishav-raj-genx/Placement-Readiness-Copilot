-- --------------------------------------------------------------------
-- 0. User Profiles Table (Student & Admin Roles)
-- --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    display_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
    github_username TEXT,
    linkedin_url TEXT,
    resume_pdf_path TEXT,
    linkedin_pdf_path TEXT,
    linkedin_text TEXT,
    leetcode_url TEXT,
    coding_profile_url TEXT,
    interview_credits INTEGER DEFAULT 3,
    is_premium BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_own_profile" ON profiles;
CREATE POLICY "select_own_profile" ON profiles FOR SELECT USING (auth.uid() = id);

DROP POLICY IF EXISTS "insert_own_profile" ON profiles;
CREATE POLICY "insert_own_profile" ON profiles FOR INSERT WITH CHECK (auth.uid() = id AND role = 'student');

DROP POLICY IF EXISTS "update_own_profile" ON profiles;
CREATE POLICY "update_own_profile" ON profiles FOR UPDATE USING (auth.uid() = id);

DROP POLICY IF EXISTS "delete_own_profile" ON profiles;
CREATE POLICY "delete_own_profile" ON profiles FOR DELETE USING (auth.uid() = id);

DROP POLICY IF EXISTS "Service role full access profiles" ON profiles;
CREATE POLICY "Service role full access profiles" ON profiles FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name, role)
    VALUES (
        NEW.id,
        COALESCE(NEW.email, ''),
        COALESCE(NULLIF(NEW.raw_user_meta_data->>'display_name', ''), split_part(COALESCE(NEW.email, ''), '@', 1), 'Student'),
        'student'
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();

CREATE OR REPLACE FUNCTION public.prevent_client_role_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF NEW.role IS DISTINCT FROM OLD.role AND auth.role() <> 'service_role' THEN
        RAISE EXCEPTION 'Only the service role may change profile roles';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS prevent_profile_role_change ON public.profiles;
CREATE TRIGGER prevent_profile_role_change
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.prevent_client_role_change();

-- --------------------------------------------------------------------
-- 1. Canonical Interview Sessions Table (Module 3 - Voice & AI Viva)
-- --------------------------------------------------------------------
-- Note: id is TEXT to support both auto-generated UUIDs and 'intv_<timestamp>'
-- session IDs generated by the Next.js platform Edge Function.
-- result is nullable because sessions are created with status 'created'
-- before the interview completes.
CREATE TABLE IF NOT EXISTS interview_sessions (
    id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
    user_id UUID DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
    student_id TEXT NOT NULL DEFAULT COALESCE(auth.uid()::text, 'unknown'),
    livekit_room_name TEXT,
    target_role TEXT,
    job_id TEXT,
    resume_id TEXT,
    config JSONB DEFAULT '{}'::jsonb,
    room_metadata JSONB,
    status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'active', 'completed', 'abandoned', 'error')),
    result JSONB,
    contract_version TEXT GENERATED ALWAYS AS (result->>'contract_version') STORED,
    interview_score NUMERIC(5, 2) GENERATED ALWAYS AS (NULLIF(result->>'interview_score', '')::numeric) STORED,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

