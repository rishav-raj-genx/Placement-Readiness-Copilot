-- View: Canonical or latest mock interview per student
-- Drop view first to avoid column rename conflict in PostgreSQL
DROP VIEW IF EXISTS latest_student_mock_interviews;
CREATE OR REPLACE VIEW latest_student_mock_interviews AS
SELECT DISTINCT ON (student_id)
    id,
    student_id,
    interview_score,
    contract_version,
    result->>'summary' AS summary,
    result->'transcript' AS transcript,
    created_at
FROM interview_sessions
WHERE (contract_version = 'v0' OR contract_version IS NULL)
ORDER BY student_id, created_at DESC;

